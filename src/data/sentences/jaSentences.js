// 90 Kalimat Grammar Bahasa Jepang Standar JLPT (30 SD Pre-N5/N5, 30 SMP N5/N4, 30 SMA N4/N3)
// Memisahkan partikel (は, が, を, に, で, へ, と, の, から, まで, より) sebagai blok susunan aktif.

function ja(
  id,
  topic,
  level,
  grammarTitle,
  grammarFormula,
  grammarNote,
  tokens,
  tokenHints,
  distractors,
  distractorHints,
  reading,
  romaji,
  indo,
  indoDistractors,
  indoAlts = [],
  targetAlts = [],
  punct = '。',
) {
  const indoPunct = indo.slice(-1);
  const indoBody = indo.slice(0, -1);
  return {
    id,
    topic,
    level,
    grammarTitle,
    grammarFormula,
    grammarNote,
    target: tokens.join('') + punct,
    tokens,
    punct,
    distractors,
    reading,
    romaji,
    pinyin: '',
    tokenHints,
    distractorHints,
    indo,
    indoTokens: indoBody.split(' '),
    indoPunct,
    indoDistractors,
    indoAlts,
    targetAlts,
  };
}


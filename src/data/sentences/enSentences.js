function en(
  id,
  topic,
  level,
  grammarTitle,
  grammarFormula,
  grammarNote,
  target,
  distractors,
  indo,
  indoDistractors,
  indoAlts = [],
  targetAlts = [],
) {
  const punct = target.slice(-1);
  const body = target.slice(0, -1);
  const indoPunct = indo.slice(-1);
  const indoBody = indo.slice(0, -1);
  return {
    id,
    topic,
    level,
    grammarTitle,
    grammarFormula,
    grammarNote,
    target,
    tokens: body.split(' '),
    punct,
    distractors,
    reading: '',
    romaji: '',
    pinyin: '',
    tokenHints: [],
    distractorHints: [],
    indo,
    indoTokens: indoBody.split(' '),
    indoPunct,
    indoDistractors,
    indoAlts,
    targetAlts,
  };
}


function zh(
  id,
  topic,
  level,
  grammarTitle,
  grammarFormula,
  grammarNote,
  tokens,
  tokenHints,
  distractors,
  distractorHints,
  pinyin,
  indo,
  indoDistractors,
  indoAlts = [],
  targetAlts = [],
  punct = '。',
) {
  const indoPunct = indo.slice(-1);
  const indoBody = indo.slice(0, -1);
  return {
    id,
    topic,
    level,
    grammarTitle,
    grammarFormula,
    grammarNote,
    target: tokens.join('') + punct,
    tokens,
    punct,
    distractors,
    reading: '',
    romaji: '',
    pinyin,
    tokenHints,
    distractorHints,
    indo,
    indoTokens: indoBody.split(' '),
    indoPunct,
    indoDistractors,
    indoAlts,
    targetAlts,
  };
}

